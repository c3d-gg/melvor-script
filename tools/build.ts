/**
 *   bun run build   bundle src/runtime -> mod/runtime.mjs
 *   bun run pack    build + zip the mod -> dist/melvor-script.zip (install via Creator Toolkit / mod.io)
 *   bun run dev     watch: rebuild on change and hot-reload the runtime inside the running game
 */
import * as esbuild from 'esbuild';
import { mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { crc32, deflateRawSync } from 'node:zlib';
import { connect } from '../src/client/index.ts';
import { setDevRuntime } from '../src/client/config.ts';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const MOD_DIR = join(ROOT, 'mod');
const RUNTIME_OUT = join(MOD_DIR, 'runtime.mjs');
const args = new Set(process.argv.slice(2));

const options: esbuild.BuildOptions = {
  entryPoints: [join(ROOT, 'src', 'runtime', 'index.ts')],
  outfile: RUNTIME_OUT,
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: ['chrome119'],
  legalComments: 'none',
  banner: { js: '// melvor-script runtime: generated by `bun run build` from src/runtime. Do not edit.' },
  logLevel: 'info',
};

async function hotReload() {
  try {
    const m = await connect({ name: 'dev-reloader', timeoutMs: 1500 });
    await m.reloadRuntime();
    await m.close();
    console.log('↻ runtime reloaded in game');
  } catch (e) {
    console.log(`(game not reachable, skipped hot reload: ${e instanceof Error ? e.message.split('\n')[0] : e})`);
  }
}

function zipDir(dir: string, out: string) {
  const files: string[] = [];
  const walk = (d: string) => {
    for (const name of readdirSync(d)) {
      const p = join(d, name);
      if (statSync(p).isDirectory()) walk(p);
      else files.push(p);
    }
  };
  walk(dir);

  const now = new Date();
  const dosTime = (now.getHours() << 11) | (now.getMinutes() << 5) | (now.getSeconds() >> 1);
  const dosDate = ((now.getFullYear() - 1980) << 9) | ((now.getMonth() + 1) << 5) | now.getDate();
  const chunks: Buffer[] = [];
  const central: Buffer[] = [];
  let offset = 0;
  for (const file of files) {
    const name = Buffer.from(relative(dir, file).split('\\').join('/'), 'utf8');
    const data = readFileSync(file);
    const deflated = deflateRawSync(data, { level: 9 });
    const crc = crc32(data) >>> 0;
    const local = Buffer.alloc(30);
    local.writeUInt32LE(0x04034b50, 0);
    local.writeUInt16LE(20, 4); // version needed
    local.writeUInt16LE(0x0800, 6); // utf-8 names
    local.writeUInt16LE(8, 8); // deflate
    local.writeUInt16LE(dosTime, 10);
    local.writeUInt16LE(dosDate, 12);
    local.writeUInt32LE(crc, 14);
    local.writeUInt32LE(deflated.length, 18);
    local.writeUInt32LE(data.length, 22);
    local.writeUInt16LE(name.length, 26);
    local.writeUInt16LE(0, 28);
    chunks.push(local, name, deflated);

    const cen = Buffer.alloc(46);
    cen.writeUInt32LE(0x02014b50, 0);
    cen.writeUInt16LE(20, 4);
    cen.writeUInt16LE(20, 6);
    cen.writeUInt16LE(0x0800, 8);
    cen.writeUInt16LE(8, 10);
    cen.writeUInt16LE(dosTime, 12);
    cen.writeUInt16LE(dosDate, 14);
    cen.writeUInt32LE(crc, 16);
    cen.writeUInt32LE(deflated.length, 20);
    cen.writeUInt32LE(data.length, 24);
    cen.writeUInt16LE(name.length, 28);
    cen.writeUInt32LE(offset, 42);
    central.push(cen, name);
    offset += local.length + name.length + deflated.length;
  }
  const cenBuf = Buffer.concat(central);
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0);
  end.writeUInt16LE(files.length, 8);
  end.writeUInt16LE(files.length, 10);
  end.writeUInt32LE(cenBuf.length, 12);
  end.writeUInt32LE(offset, 16);
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, Buffer.concat([...chunks, cenBuf, end]));
  console.log(`packed ${files.length} files -> ${relative(ROOT, out)}`);
}

async function main() {
  if (args.has('--watch')) {
    setDevRuntime(RUNTIME_OUT);
    console.log(`dev: the game will load the runtime from ${RUNTIME_OUT}`);
    console.log('     (run `bun run melvor use-bundled` to go back to the copy inside the mod zip)');
    const ctx = await esbuild.context({
      ...options,
      plugins: [
        {
          name: 'hot-reload',
          setup(build) {
            // Also runs after the first build, which switches a running game from the bundled runtime to this one.
            build.onEnd(async (result) => {
              if (result.errors.length === 0) await hotReload();
            });
          },
        },
      ],
    });
    await ctx.watch();
    return;
  }
  await esbuild.build(options);
  if (args.has('--pack')) zipDir(MOD_DIR, join(ROOT, 'dist', 'melvor-script.zip'));
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
